allprojects {
    repositories {
        google()
        mavenCentral()
    }
}

val newBuildDir: Directory =
    rootProject.layout.buildDirectory
        .dir("../../build")
        .get()
rootProject.layout.buildDirectory.value(newBuildDir)

subprojects {
    val newSubprojectBuildDir: Directory = newBuildDir.dir(project.name)
    project.layout.buildDirectory.value(newSubprojectBuildDir)
    // Flutter's integration_test plugin declares runner as 1.2+. Pin the
    // resolved compatible version so ordinary app builds are reproducible and
    // do not require remote Maven metadata just to select a version.
    configurations.configureEach {
        resolutionStrategy.force("androidx.test:runner:1.3.0")
    }
}
subprojects {
    project.evaluationDependsOn(":app")
}

tasks.register<Delete>("clean") {
    delete(rootProject.layout.buildDirectory)
}
